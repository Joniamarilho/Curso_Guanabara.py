import math
an = float(input('Qual o ângulo :'))
seno = math.sin(math.radians(an))
print(f'O ângulo de {an} tem o seno de {seno}')
cosseno = math.cos(math.radians(an))
print(f'O ãngulo de {an} tem o cosseno de {cosseno}')
tangente = math.tan(math.radians(an))
print(f'O ângulo de {an} tem o tangente de {tangente}')
